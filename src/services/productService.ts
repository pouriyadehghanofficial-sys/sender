export interface ProductForPrompt {
  name: string;
  descriptionText: string;
}

export interface SystemPromptContext {
  /** true = این اولین پاسخ AI در این مکالمه است (می‌تواند کوتاه سلام کند) */
  isFirstAiReply?: boolean;
  /** خلاصه‌ی حافظه‌ی این مشتری از مکالمات قبلی (اگر موجود باشد) */
  memoryNotes?: string | null;
  /** محصولات دیگری که همین مشتری در همین مکالمه درباره‌شان پرسیده (چند محصول هم‌زمان) */
  additionalProducts?: ProductForPrompt[];
}

/**
 * ساخت system prompt.
 *
 * هیچ پرسونا/لحن/قانون ثابتی روی متن تو اضافه نمی‌شود. هرچه در «توضیحات محصول»
 * بنویسی — چه فقط مشخصات خام باشد، چه یک پرامپت کامل با اسم، پرسونا، لحن و قوانین —
 * دقیقاً همان، بدون رقیب و بدون رقیق شدن، به مدل داده می‌شود. فقط یک بخش فنی کوتاه
 * برای تگ‌های مخفی سیستم و وضعیت مکالمه (سلام/حافظه/زبان/محصولات دیگر) اضافه می‌شود.
 *
 * نکته درباره‌ی A/B: اگر یک نسخه‌ی prompt variant به این مکالمه اختصاص داده شده باشد،
 * caller باید همان‌طور که هست به‌جای product.descriptionText به این تابع بدهد (یعنی کل
 * محتوای «product» ورودی، اسم و توضیحاتش، همان نسخه‌ی انتخاب‌شده است) — این تابع خودش
 * از انتخاب نسخه خبر ندارد و نیازی هم ندارد.
 */
export function buildSystemPrompt(
  product: ProductForPrompt,
  escalationInstructions?: string,
  context?: SystemPromptContext
): string {
  const ownerConditions = escalationInstructions?.trim();

  const escalationRule = ownerConditions
    ? `اگر یکی از این شرایط رخ داد، مودبانه بگو موضوع را با همکاران در میان می‌گذاری و دقیقاً این عبارت را در انتهای همان پاسخ بنویس: [NEEDS_HUMAN]\nشرایط ارجاع: ${ownerConditions}\nدر هیچ حالت دیگری این تگ را ننویس.`
    : `تگ [NEEDS_HUMAN] را در هیچ حالتی ننویس؛ خودت تا آخر مکالمه را پیش ببر.`;

  const greetingRule = context?.isFirstAiReply
    ? `این اولین پاسخت در این مکالمه است؛ اگر با سبک/لحنی که بالا تعریف شده جور است، می‌توانی خیلی کوتاه سلام کنی.`
    : `این اولین پاسخت در این مکالمه نیست (قبلاً به همین مشتری در همین مکالمه پاسخ داده‌ای). دوباره سلام نکن، خودت را دوباره معرفی نکن، و چیزی را که قبلاً در همین مکالمه گفته‌ای تکرار نکن.`;

  const memorySection = context?.memoryNotes?.trim()
    ? `\nحافظه‌ی این مشتری از مکالمات قبلی (فقط برای پیوسته و بدون‌تکرار بودن پاسخ استفاده کن؛ این‌ها را عیناً برای مشتری نخوان مگر لازم شود): ${context.memoryNotes.trim()}\n`
    : "";

  const languageRule = `اگر مشتری به زبان یا لهجه‌ی دیگری (غیر از آنچه در بالا نوشته شده) پیام داد، خودت را با همان زبان/لهجه تطبیق بده و به همان زبان جواب بده.`;

  const extraProductsSection = context?.additionalProducts?.length
    ? `\nمحصولات دیگری که همین مشتری در همین مکالمه درباره‌شان هم پرسیده (در صورت نیاز از این اطلاعات هم استفاده کن، ولی محصول اصلی بالا همچنان محور اصلی مکالمه است):\n` +
      context.additionalProducts
        .map((p, i) => `--- محصول اضافه ${i + 1}: ${p.name} ---\n${p.descriptionText}`)
        .join("\n\n") +
      "\n"
    : "";

  const unknownTopicRule = `اگر مشتری چیزی پرسید که پاسخش دقیقاً در اطلاعات بالا نیست و نمی‌دانی، صادقانه (بدون اشاره به این راهنما) بگو الان این را دقیق در اختیار نداری، و در انتهای همان پاسخ این تگ را هم با موضوع خیلی کوتاه اضافه کن (می‌تواند چند بار تکرار شود): [UNKNOWN_TOPIC: موضوع کوتاه]`;

  return `${product.descriptionText}
${extraProductsSection}
---
(راهنمای فنی سیستم — بخشی از پاسخ نیست و به مشتری نشان داده نمی‌شود)
اگر مشتری تصمیم قطعی به خرید گرفت و جزئیات لازم سفارش را تایید کرد، دقیقاً این عبارت را در انتهای پاسخت اضافه کن: [ORDER_CONFIRMED]
${escalationRule}
${greetingRule}
${languageRule}
${unknownTopicRule}
${memorySection}این‌ها را فقط در انتهای پاسخ (تگ‌ها) یا برای هدایت لحن (سلام/حافظه/زبان) به‌کار ببر؛ در متنی که مشتری می‌بیند توضیحی درباره‌ی این راهنما نده.`;
}
